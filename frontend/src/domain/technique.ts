export interface TechniqueImages {
  /** Начало и конец движения; у некоторых упражнений бокса — один кадр. */
  frames: string[]
  /** Подпись об источнике — её требует лицензия рисунков. */
  credit: string
  /** `boxing` — вертикальные кадры, их нельзя обрезать как обычные фото. */
  kind: 'drawing' | 'photo' | 'boxing'
}

const slug = (exercise: Pick<Exercise, 'id'>) => exercise.id.replace(/^builtin-/, '')

/** Картинки техники: рисунок, а если его нет — фото; null — картинок нет. */
export function techniqueImages(exercise: Pick<Exercise, 'id'>): TechniqueImages | null {
  const id = slug(exercise)
  const boxing = BOXING[id]
  if (boxing) {
    const base = `${import.meta.env.BASE_URL}technique/boxing/${id}`
    return {
      frames: Array.from({ length: boxing.frames }, (_, i) => `${base}-${i}.webp`),
      credit: boxing.credit,
      kind: 'boxing',
    }
  }
  const kind = DRAWINGS.has(id) ? 'drawing' : PHOTOS.has(id) ? 'photo' : null
  if (!kind) return null
  const base = `${import.meta.env.BASE_URL}technique/${kind === 'drawing' ? 'drawings' : 'photos'}/${id}`
  return {
    frames: [`${base}-0.webp`, `${base}-1.webp`],
    credit:
      kind === 'drawing'
        ? 'Рисунки: Everkinetic, Greg Priday — CC BY-SA 4.0'
        : 'Фото: free-exercise-db — общественное достояние',
    kind,
  }
}

/** Подсказки по технике для упражнения; у своих и редких упражнений их нет. */
export function techniqueCues(exercise: Pick<Exercise, 'id'>): string[] {
  return CUES[slug(exercise)] ?? []
}

/** Поиск картинок в Яндексе: техника и работающие мышцы по названию упражнения. */
export function techniqueSearchUrl(exercise: Pick<Exercise, 'name'>): string {
  return `https://yandex.ru/images/search?text=${encodeURIComponent(`${exercise.name} техника мышцы`)}`
}
