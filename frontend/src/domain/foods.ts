export const FOODS: Food[] = TABLE.map(([name, calories, protein, fat, carbs]) => ({
  name,
  per100: { calories, protein, fat, carbs },
}))

/** Для сравнения: регистр и «ё» не важны. */
export function normalizeName(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е').trim()
}

const words = (s: string) =>
  normalizeName(s)
    .split(/[^a-zа-я0-9]+/)
    .filter(Boolean)

/**
 * Свои продукты из записей с весом порции: значения переводятся на 100 г.
 * Записи ожидаются от новых к старым — из одинаковых названий берётся последняя.
 */
export function foodsFromMeals(meals: Meal[]): Food[] {
  const seen = new Set<string>()
  const result: Food[] = []
  for (const m of meals) {
    const key = normalizeName(m.name)
    if (!m.grams || seen.has(key)) continue
    seen.add(key)
    result.push({ name: m.name, per100: scaleNutrients(m, m.grams, 100), own: true })
  }
  return result
}

/**
 * Продукты, подходящие под ввод: каждое слово запроса — начало какого-то слова в названии
 * («гре вар» → «Гречка варёная»). Сначала свои, внутри — те, что начинаются с запроса.
 */
export function searchFoods(query: string, own: Food[], limit = 6): Food[] {
  const q = words(query)
  if (q.length === 0) return []
  const qText = normalizeName(query)
  const matches = (f: Food) => {
    const w = words(f.name)
    return q.every((part) => w.some((x) => x.startsWith(part)))
  }
  const rank = (f: Food) => (normalizeName(f.name).startsWith(qText) ? 0 : 1)
  const ownHits = own.filter(matches)
  const ownNames = new Set(ownHits.map((f) => normalizeName(f.name)))
  const catalogHits = FOODS.filter((f) => !ownNames.has(normalizeName(f.name)) && matches(f))
  const sorted = (list: Food[]) =>
    list
      .map((f, i) => ({ f, i }))
      .sort((a, b) => rank(a.f) - rank(b.f) || a.i - b.i)
      .map((x) => x.f)
  return [...sorted(ownHits), ...sorted(catalogHits)].slice(0, limit)
}
